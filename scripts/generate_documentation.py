"""Generate the data-driven documentation from the registries and the latest reports.

    python scripts/generate_documentation.py

Writes documentation/BOARD_CATALOG.md, FORMULAS.md, SOURCES.md, VALIDATION_REPORT.md.
Hand-written documents (MANUFACTURING_GUIDE, MECHANICAL_DESIGN, UNRESOLVED_DECISIONS) are not touched.
"""
import json
import sys
import tomllib
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from deck.config import BOARDS, FAB, FORMULAS, ROOT, board_dir  # noqa: E402

DOC = ROOT / "documentation"
REP = ROOT / "output" / "fabrication_reports"
GEN = "<!-- generated by scripts/generate_documentation.py - do not edit by hand -->\n\n"


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def jload(p):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def catalog():
    s = [GEN, "# Board catalog\n\n15 independent KiCad 10 boards, 85.60 × 53.98 × 1.0 mm, 2 layers. "
         "Previews are KiCad 3D renders (`output/documentation/previews/`).\n"]
    for c in BOARDS:
        meta = jload(board_dir(c) / "board_meta.json") or {}
        drc = jload(REP / c["dir"] / "drc.json")
        val = jload(REP / c["dir"] / "validation.json") or []
        s.append(f"\n## {c['id']:02d} {c['title']}\n\n`boards/{c['dir']}/{c['dir']}.kicad_pcb` - "
                 f"generator `scripts/deck/cards/{c['module']}.py`\n\n")
        if drc:
            sev = Counter(v["severity"] for v in drc["violations"])
            s.append(f"- DRC: {sev['error']} errors, {sev['warning']} warnings, "
                     f"{len(drc.get('unconnected_items', []))} unconnected ({drc.get('date', '')})\n")
        s.append(f"- validation: {dict(Counter(v['status'] for v in val))}\n")
        panels = meta.get("reserved_panels", {})
        for side, name in (("F", "front"), ("B", "back")):
            names = [n for n in panels.get(side, []) if n not in ("ring hole", "header", "footer")]
            s.append(f"- {name}: {', '.join(names)}\n")
        if meta.get("packages"):
            s.append(f"- KiCad footprints: {', '.join(f'`{p}`' for p in meta['packages'])}\n")
        s.append(f"\n![front](../output/documentation/previews/{c['dir']}_top.png)\n"
                 f"![back](../output/documentation/previews/{c['dir']}_bottom.png)\n")
    return "".join(s)


def formulas():
    s = [GEN, "# Formula registry\n\nSource: `data/formulas/formulas.toml`. Status: STANDARD = definition / "
         "textbook identity, MODEL = approximation with stated validity, RULE = rule of thumb. "
         "Equations use KiCad markup (`_{}` subscript, `^{}` superscript, `~{}` overbar).\n"]
    for k, f in FORMULAS.items():
        s.append(f"\n## `{k}` - {f['status']}\n\n`{f['eq']}`\n\n- variables: {f['vars']}\n"
                 f"- assumptions: {f['assumptions']}\n- source: {f['source']}\n")
        if "test" in f:
            s.append(f"- checked by: `{f['test']}`\n")
    return "".join(s)


def sources():
    rows = []
    for p in sorted((ROOT / "data").rglob("*.toml")):
        rel = p.relative_to(ROOT).as_posix()
        d = tomllib.loads(p.read_text(encoding="utf-8"))
        if p.name == "formulas.toml":
            st = Counter(v["status"] for v in d.values())
            rows.append([rel, "(all)", f"{len(d)} formulas {dict(st)}, see FORMULAS.md", "-"])
            continue
        for k, v in d.items():
            items = v if isinstance(v, list) else [v]
            for it in items:
                if not isinstance(it, dict):
                    continue
                name = it.get("key") or it.get("title") or k
                for sk, stk in (("source", "status"), ("power_source", "power_status")):
                    if sk in it or stk in it:
                        rows.append([rel, name, it.get(sk, "(see note)"), it.get(stk, it.get("body_status", "?"))])
    fab = FAB["reference_fab"]
    rows.append(["project/manufacturing_constraints.toml", f"{fab['name']} capabilities", fab["source"],
                 f"VERIFIED (read {fab['accessed']}; re-confirm before ordering)"])
    st = Counter(str(r[3]).split()[0] for r in rows if r[3] != "-")
    return (GEN + "# Source registry\n\nEvery printed value comes from one of these entries. Status: VERIFIED = "
            "primary document read; CROSS-CHECKED = compared automatically with an independent source "
            "(e.g. KiCad F.Fab bodies); SECONDARY = widely tabulated, primary not read; UNVERIFIED = must not "
            "be relied on. Standards are cited, never reproduced.\n\n"
            f"Totals: {dict(st)}\n\n" + table(["file", "entry", "source", "status"], rows))


def validation():
    s = [GEN, "# Validation report\n\nProduced by `scripts/validate_boards.py` (reads the .kicad_pcb files "
         "independently of the generator) and `kicad-cli pcb drc`. FAB = needs manufacturer confirmation, "
         "REVIEW = needs a human.\n\n"]
    tot = Counter()
    for c in BOARDS:
        val = jload(REP / c["dir"] / "validation.json") or []
        tot.update(v["status"] for v in val)
        s.append(f"## {c['id']:02d} {c['title']}\n\n" + table(["check", "status", "detail"],
                 [[v["check"], v["status"], v["detail"]] for v in val]) + "\n")
    cons = jload(REP / "consistency.json")
    s.insert(1, f"Totals: {dict(tot)}" + (f"; cross-card: {cons['check']} {cons['status']} ({cons['detail']})"
                                          if cons else "") + "\n\n")
    return "".join(s)


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    DOC.mkdir(exist_ok=True)
    for name, fn in (("BOARD_CATALOG", catalog), ("FORMULAS", formulas), ("SOURCES", sources),
                     ("VALIDATION_REPORT", validation)):
        (DOC / f"{name}.md").write_text(fn(), encoding="utf-8")
        print(f"documentation/{name}.md")


if __name__ == "__main__":
    main()
